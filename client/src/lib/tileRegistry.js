/**
 * Tile registry — the single place that describes every tile type.
 *
 * For each type:
 *   label       name shown in the editor's "Add" menu
 *   icon        BrandBadge platform key (or UI icon name via `uiIcon`)
 *   component   React component that renders the tile ({ tile, shape })
 *   layout      default size for new tiles (w = columns 1–4, h = rows 1–8,
 *               where h=2 is a square and h=1 a slim button bar) plus
 *               optional min/max limits (minW, maxW, minH, maxH)
 *   defaults    initial `data` for new tiles
 *   fields      form fields for the tile editor (see editor/TileEditor.jsx)
 *
 * Adding a new tile type = add a component, an entry here, and the same
 * field names in server/src/lib/validate.js (TILE_SCHEMAS).
 */
